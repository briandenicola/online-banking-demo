"""The golden artifact: ONE JSON file of REAL backend-emitted approval envelopes.

Cross-language drift is the recurring defect of this epic — the envelope has been stated three
times (the design doc, the shipped TypeScript + demo fixture, and this service) and the recorded
demo only ever proved the fixture against itself, never the service. This test freezes what the
service ACTUALLY emits into ``tests/fixtures/copilot-wire-envelopes.json`` (repo root), so both
sides read one file instead of agreeing with themselves:

  * this Python test asserts the service emits exactly this wire shape, and
  * a UI test (Linus) feeds the SAME file through the single mapper ``authorityWire.toApproval``
    and the real reducer, asserting the approval lands in the store with BOTH assessments and
    with rendered, material payload rows.

The file is generated by driving the REAL planner + fan-out engine (the default
``deterministic_decider`` is replaced here by a fixed dissenting decider so the golden captures the
demo's peak: a genuine primary/supervisor disagreement). Only the volatile envelope fields (`id`,
`ts`) are stripped; everything the UI consumes is preserved verbatim.

Regenerate intentionally with ``COPILOT_REGEN_GOLDEN=1 pytest tests/test_golden_wire_envelopes.py``.
A missing golden file THROWS (it is never skipped) — a golden nobody has run is not a contract.
"""

