def required_handles() -> list[str]:
    """The distinct subject handles this corpus needs resolved."""
    seen: list[str] = []
    for case in CASES:
        if case["subject"] not in seen:
            seen.append(case["subject"])
    return seen


def resolve_cases(resolved_subjects: dict, cases: list[dict] | None = None) -> list[dict]:
    """Return copies of the cases with ``account`` set to today's live id.

    ``CASES`` itself is never mutated, so a second resolution cannot inherit a stale id from a
    first one. An unresolved handle raises rather than producing a case that would run against
    ``None`` and be recorded as an instrument failure.
    """
    out: list[dict] = []
    for case in (cases if cases is not None else CASES):
        subject = resolved_subjects.get(case["subject"])
        if subject is None:
            raise RuntimeError(
                f"case {case['id']!r} needs subject {case['subject']!r}, which was not resolved "
                "against the live deployment. Resolve it with seed_subjects.resolve_subjects() "
                "rather than substituting a literal id."
            )
        resolved = dict(case)
        resolved["account"] = subject.require_id()
        resolved["subjectOwner"] = subject.owner
        resolved["subjectAccountType"] = subject.account_type
        out.append(resolved)
    return out


def assert_amounts_reach_dual_control(threshold: float) -> None:
    """Every case must clear the live ``balance_adjustment_dual_control_amount`` (``gte``).

    Below it the action settles at L1, there is no fan-out and no supervisor opinion — the case
    would produce an instrument failure that looks like a service defect. Checked against the
    LIVE policy so that a threshold change is reported here rather than discovered as 32
    unexplained instrument failures.
    """
    low = [(c["id"], c["amount"]) for c in CASES if float(c["amount"]) < threshold]
    if low:
        raise RuntimeError(
            f"these cases fall below the live balance_adjustment_dual_control_amount "
            f"({threshold}) and would never reach L2 or produce a supervisor opinion: {low}"
        )


