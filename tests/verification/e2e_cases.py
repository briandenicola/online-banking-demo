def _amount(handle: str, description: str) -> float:
    """The amount of the one seeded transaction identified by ``description``.

    An exact description match wins; otherwise the description is treated as a fragment. Either
    way exactly one transaction must match. This raises rather than guessing: if the dataset
    stops guaranteeing a transaction a case is built on, that case must not silently become
    ungrounded — the corpus should refuse to import.
    """
    txns = SUBJECTS[handle].transactions
    matches = [t["amount"] for t in txns if t["description"].casefold() == description.casefold()]
    if not matches:
        matches = [t["amount"] for t in txns
                   if description.casefold() in t["description"].casefold()]
    if len(matches) != 1:
        raise RuntimeError(
            f"config/demo-dataset.json no longer guarantees exactly one transaction matching "
            f"{description!r} on {handle} (found {len(matches)}). A case in this "
            "corpus is built on that transaction and would silently become ungrounded."
        )
    return abs(matches[0])


def _money(value: float) -> str:
    return f"{value:,.2f}"


def _decimal(value: float) -> str:
    return f"{value:.2f}"


